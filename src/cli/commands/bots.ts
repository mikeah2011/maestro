import { existsSync, mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import type { Command } from 'commander';
import chalk from 'chalk';
import { loadConfig, ConfigError } from '../../config';

const NOT_YET = 4;

function notYet(action: string): never {
  console.error(chalk.yellow(`maestro bots ${action}: not yet implemented (lands in M4)`));
  process.exit(NOT_YET);
}

// ─── Workflow template ────────────────────────────────────────────────────────

/**
 * Build the auto-approve workflow YAML.
 *
 * Logic:
 *   - "satisfied" bots: bots that post COMMENTED reviews with "generated no new comments"
 *     (GitHub Copilot pattern).  Treated as passing even without a formal APPROVE.
 *   - "approving" bots: all other watched bots — must reach APPROVED state.
 *
 * When all watched bots have either satisfied or approved, the workflow submits
 * a formal APPROVE review on behalf of the GITHUB_TOKEN.
 */
function buildWorkflow(watchedBots: string[]): string {
  // Three mutually-exclusive bot categories (checked in priority order):
  //   1. satisfied   — post COMMENTED + "generated no new comments" (Copilot pattern)
  //   2. reviewedOnly — can only comment, never formally approve (Codex pattern)
  //   3. approving   — must reach APPROVED state (CodeRabbit, Ellipsis, etc.)
  const satisfiedPatternBots = ['copilot-pull-request-reviewer', 'github-advanced-security'];
  const reviewedOnlyBots = ['chatgpt-codex-connector[bot]', 'chatgpt-codex-connector'];

  const isSatisfiedBot = (b: string) => satisfiedPatternBots.some((p) => b.includes(p));
  const isReviewedOnlyBot = (b: string) => reviewedOnlyBots.some((p) => b === p || b === p.replace('[bot]', ''));

  // Strip [bot] suffix for comparison so conditions work regardless of whether
  // the caller passed "foo" or "foo[bot]" — GitHub API returns the [bot] form.
  const stripBot = (b: string) => b.replace(/\[bot\]$/, '');

  const satisfiedChecks = watchedBots
    .filter(isSatisfiedBot)
    .map((b) => `reviews.some(r => r.user.login.replace('[bot]', '') === '${stripBot(b)}' && r.body?.includes('generated no new comments'))`);

  const reviewedChecks = watchedBots
    .filter((b) => !isSatisfiedBot(b) && isReviewedOnlyBot(b))
    .map((b) => `reviews.some(r => r.user.login.replace('[bot]', '') === '${stripBot(b)}')`);

  const approvedChecks = watchedBots
    .filter((b) => !isSatisfiedBot(b) && !isReviewedOnlyBot(b))
    .map((b) => `reviews.some(r => r.user.login.replace('[bot]', '') === '${stripBot(b)}' && r.state === 'APPROVED')`);

  const allChecks = [...satisfiedChecks, ...reviewedChecks, ...approvedChecks];
  const conditionLines = allChecks.length > 0
    ? allChecks.map((c, i) => `            ${i === 0 ? '' : '&& '}${c}`).join('\n')
    : '            true // no bots configured — always approve';

  const botList = watchedBots.length > 0
    ? watchedBots.map((b) => `#   - ${b}`).join('\n')
    : '#   (none configured — watching all bots)';

  return `# Auto-generated by \`maestro bots setup\`
# Commit this file to enable automatic PR approval when all watched bots are satisfied
# AND all review threads are resolved.
#
# Watched bots:
${botList}
#
# To regenerate: maestro bots setup --force

name: maestro-auto-approve

on:
  pull_request_review:
    types: [submitted]
  issue_comment:
    types: [created]

permissions:
  pull-requests: write

jobs:
  auto-approve:
    runs-on: ubuntu-latest
    # Only run on pull request events, not plain issue comments
    if: github.event.pull_request != null || github.event.issue.pull_request != null
    steps:
      - uses: actions/github-script@v7
        with:
          github-token: \${{ secrets.GITHUB_TOKEN }}
          script: |
            const prNumber = context.payload.pull_request?.number
              ?? context.payload.issue?.number;
            if (!prNumber) return;

            // ── 1. Check bot satisfaction ──────────────────────────────────
            const { data: reviews } = await github.rest.pulls.listReviews({
              owner: context.repo.owner,
              repo: context.repo.repo,
              pull_number: prNumber,
            });

            // Keep only the latest review per bot
            const latestByBot = new Map();
            for (const r of reviews) {
              const existing = latestByBot.get(r.user.login);
              if (!existing || new Date(r.submitted_at) > new Date(existing.submitted_at)) {
                latestByBot.set(r.user.login, r);
              }
            }
            reviews.length = 0;
            reviews.push(...latestByBot.values());

            const allSatisfied =
${conditionLines};

            if (!allSatisfied) return;

            // ── 2. Guard: all review threads must be resolved ──────────────
            const threadData = await github.graphql(\`
              query($owner: String!, $repo: String!, $number: Int!) {
                repository(owner: $owner, name: $repo) {
                  pullRequest(number: $number) {
                    reviewThreads(first: 100) {
                      nodes { isResolved }
                    }
                  }
                }
              }
            \`, {
              owner: context.repo.owner,
              repo: context.repo.repo,
              number: prNumber,
            });

            const threads = threadData.repository.pullRequest.reviewThreads.nodes;
            const hasUnresolved = threads.some(t => !t.isResolved);
            if (hasUnresolved) return; // maestro loop will resolve first

            // ── 3. Approve (idempotent) ────────────────────────────────────
            const alreadyApproved = reviews.some(
              r => r.user.login === 'github-actions[bot]' && r.state === 'APPROVED'
            );
            if (alreadyApproved) return;

            await github.rest.pulls.createReview({
              owner: context.repo.owner,
              repo: context.repo.repo,
              pull_number: prNumber,
              event: 'APPROVE',
              body: '✅ 所有監控機器人均已審查完畢且討論串已全數解決，自動核准。',
            });
`;
}

// ─── Command registration ─────────────────────────────────────────────────────

export function registerBotsCommand(program: Command): void {
  const bots = program.command('bots').description('inspect and manage the bot registry');

  bots
    .command('list')
    .description('list configured + curated review bots')
    .action(() => notYet('list'));

  bots
    .command('register')
    .description('register a self-hosted or custom bot for detection')
    .requiredOption('--login <login>', 'bot login as it appears on the platform')
    .option('--treat-as <mode>', 'blocking | advisory', 'advisory')
    .action(() => notYet('register'));

  bots
    .command('inspect')
    .description('show the BotRegistry parser output for a sample comment')
    .requiredOption('--bot <login>', 'bot login')
    .requiredOption('--comment <file>', 'path to a file with the bot comment body')
    .action(() => notYet('inspect'));

  bots
    .command('setup')
    .description('scaffold .github/workflows/maestro-auto-approve.yml for auto-approval')
    .option('--bots <logins>', 'comma-separated bot logins to watch (overrides config)')
    .option('--force', 'overwrite existing workflow file')
    .action((opts: { bots?: string; force?: boolean }) => {
      // Load config for default bot list
      let configBots: string[] = [];
      try {
        const config = loadConfig();
        configBots = config.bots?.watch ?? [];
      } catch (err) {
        if (!(err instanceof ConfigError)) throw err;
        // Config missing is fine — we'll use CLI overrides or defaults
      }

      const watchedBots = opts.bots
        ? opts.bots.split(',').map((s) => s.trim()).filter(Boolean)
        : configBots;

      const workflowDir = join(process.cwd(), '.github', 'workflows');
      const workflowPath = join(workflowDir, 'maestro-auto-approve.yml');

      if (existsSync(workflowPath) && !opts.force) {
        console.error(chalk.yellow(`workflow already exists: ${workflowPath}`));
        console.error(chalk.gray('Use --force to overwrite.'));
        process.exit(1);
      }

      mkdirSync(workflowDir, { recursive: true });
      writeFileSync(workflowPath, buildWorkflow(watchedBots), 'utf8');

      console.log(chalk.green(`✓ 已產生 ${workflowPath}`));
      console.log('');
      console.log(chalk.bold('下一步：'));
      console.log(chalk.cyan('  git add .github/workflows/maestro-auto-approve.yml'));
      console.log(chalk.cyan('  git commit -m "ci: add maestro auto-approve workflow"'));
      console.log(chalk.cyan('  git push'));
      console.log('');
      if (watchedBots.length === 0) {
        console.log(chalk.yellow('提示：未指定監控 bot，工作流程將對所有 bot 的審查結果做出回應。'));
        console.log(chalk.gray('可使用 --bots 指定，例如：maestro bots setup --bots copilot-pull-request-reviewer,chatgpt-codex-connector'));
      } else {
        console.log(chalk.gray(`監控 bot：${watchedBots.join(', ')}`));
      }
    });
}
